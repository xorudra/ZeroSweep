import { describe, expect, it } from "vitest";
import { parseJsonLines } from "../recon/parsers-common";
import { parseSitemapXml } from "../webdiscovery/classify";
import { parseXmlLite } from "../network/xml-lite";
import { parseSpecDocument } from "../api/import-security";

/**
 * Parser robustness fuzzing (Prompt 39 §88/§89).
 *
 * Critical scanner/importer parsers consume UNTRUSTED bytes (tool output
 * from a scanned target can be attacker-shaped). The contract under
 * test: for arbitrary malformed, truncated, mutated and oversized
 * inputs, a parser must either return a (possibly empty/partial)
 * result or throw an ordinary typed Error — never a RangeError
 * (stack/size blowup), never a hang, never a non-Error throw. Inputs
 * are generated by a deterministic PRNG so failures reproduce exactly.
 */

// mulberry32 — tiny deterministic PRNG; the seed makes every case stable.
function prng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const SEEDS: Record<string, string> = {
  jsonl: '{"template-id":"x","info":{"severity":"high"}}\n{"template-id":"y"}\n',
  xml: '<?xml version="1.0"?><nmaprun><host><address addr="192.0.2.1"/><ports><port protocol="tcp" portid="443"><state state="open"/></port></ports></host></nmaprun>',
  spec: '{"openapi":"3.0.0","info":{"title":"t","version":"1"},"paths":{"/a":{"get":{"responses":{"200":{"description":"ok"}}}}}}',
};

function mutate(rand: () => number, input: string): string {
  let s = input;
  const ops = 1 + Math.floor(rand() * 6);
  for (let i = 0; i < ops; i++) {
    const op = Math.floor(rand() * 5);
    if (s.length === 0) break;
    const pos = Math.floor(rand() * s.length);
    if (op === 0) s = s.slice(0, pos); // truncate
    else if (op === 1) s = s.slice(0, pos) + s.slice(pos + 1 + Math.floor(rand() * 8)); // delete run
    else if (op === 2) s = s.slice(0, pos) + String.fromCharCode(Math.floor(rand() * 0x2fff)) + s.slice(pos); // inject char
    else if (op === 3) s = s + s.slice(0, Math.floor(rand() * s.length)); // duplicate prefix
    else s = s.split("").map((c) => (rand() < 0.03 ? "\u0000" : c)).join(""); // NUL sprinkle
  }
  return s;
}

function assertParserContract(name: string, fn: (input: string) => unknown, seedText: string) {
  const rand = prng(0xC0FFEE);
  for (let i = 0; i < 300; i++) {
    const input = mutate(rand, seedText);
    try {
      const out = fn(input);
      expect(out === undefined || typeof out === "object" || typeof out === "string").toBe(true);
    } catch (err) {
      // Typed errors are an acceptable outcome; runtime blowups are not.
      expect(err).toBeInstanceOf(Error);
      expect(err).not.toBeInstanceOf(RangeError);
      expect((err as Error).message ?? "").not.toMatch(/call stack|out of memory/i);
    }
  }
  // Fixed hostile corpus: pathological shapes seen in the wild.
  const hostile = [
    "", "\u0000".repeat(1024), "<".repeat(100_000), "{".repeat(100_000),
    '{"a":'.repeat(10_000), "<a>".repeat(20_000) + "</a>".repeat(20_000),
    "not json at all\n".repeat(5_000), "þÿ binary \x89PNG\r\n",
  ];
  for (const input of hostile) {
    try { fn(input); } catch (err) { expect(err).toBeInstanceOf(Error); expect(err).not.toBeInstanceOf(RangeError); }
  }
}

describe("parser fuzzing (§88)", () => {
  it("JSONL scanner-output parser survives malformed input", () => {
    assertParserContract("parseJsonLines", (s) => parseJsonLines(s, "fuzz"), SEEDS.jsonl);
  });

  it("XML (nmap-style) parser survives malformed input", () => {
    assertParserContract("parseXmlLite", (s) => parseXmlLite(s), SEEDS.xml);
  });

  it("sitemap XML parser survives malformed input", () => {
    assertParserContract("parseSitemapXml", (s) => parseSitemapXml(s), SEEDS.xml);
  });

  it("API spec importer survives malformed input", () => {
    assertParserContract("parseSpecDocument", (s) => parseSpecDocument(s), SEEDS.spec);
  });

  it("parsers bound their work on oversized input (§89)", () => {
    const big = SEEDS.jsonl.repeat(50_000); // ~2.5 MB of JSONL
    const t0 = Date.now();
    const out = parseJsonLines(big, "fuzz");
    expect(Date.now() - t0).toBeLessThan(10_000);
    expect(Array.isArray(out.records)).toBe(true);
  });
});
