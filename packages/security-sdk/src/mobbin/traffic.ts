import { redactMobileSecretValues } from "../mobile/patterns";

/**
 * Prompt 35 §88–§93 — mobile traffic analysis governance.
 *
 * Capture is scoped to the authorized test application / device /
 * session (§90) — traffic from anything else is out of scope by
 * construction. Everything persisted or shown passes §91 redaction:
 * Authorization, Cookie, tokens, passwords, API keys and personal
 * data fields are removed before storage, logs, reports or AI
 * context (§154). Observed endpoints correlate to the API inventory
 * as DISCOVERED_REFERENCE — they are never auto-scanned (§92).
 */

const SENSITIVE_HEADER_NAMES = new Set([
  "authorization", "cookie", "set-cookie", "x-api-key", "api-key",
  "x-auth-token", "x-session-token", "proxy-authorization",
]);
const SENSITIVE_FIELD_RE = /(password|passwd|pwd|secret|token|api[-_]?key|session|ssn|credit[-_]?card|cvv|otp|pin)/i;

export interface TrafficHeader { name: string; value: string }
export interface TrafficRecordInput {
  method: string;
  url: string;
  requestHeaders?: TrafficHeader[];
  responseHeaders?: TrafficHeader[];
  /** Host that generated the traffic — must match the session scope. */
  sourceApp: string;
  sourceDeviceId?: string | null;
  tls?: { version?: string; certificateValid?: boolean; cleartext?: boolean };
}

export function redactTrafficHeaders(headers: TrafficHeader[] = []): TrafficHeader[] {
  return headers.map((h) => SENSITIVE_HEADER_NAMES.has(h.name.toLowerCase())
    ? { name: h.name, value: "<redacted>" }
    : { name: h.name, value: redactMobileSecretValues(h.value) });
}

/** Redact sensitive fields from a JSON-ish body, returning bounded,
 *  secret-free text. Bodies are evidence summaries, never raw
 *  capture dumps (§91). */
export function redactTrafficBody(body: string, maxLen = 2048): string {
  let out = body;
  try {
    const parsed = JSON.parse(body) as unknown;
    const walk = (v: unknown): unknown => {
      if (Array.isArray(v)) return v.map(walk);
      if (v && typeof v === "object") {
        const rec: Record<string, unknown> = {};
        for (const [k, val] of Object.entries(v as Record<string, unknown>)) {
          rec[k] = SENSITIVE_FIELD_RE.test(k) ? "<redacted>" : walk(val);
        }
        return rec;
      }
      return v;
    };
    out = JSON.stringify(walk(parsed));
  } catch {
    // not JSON — fall through to pattern redaction
  }
  // §91: bearer credentials are redacted wherever they appear in a
  // body — the V1 secret patterns cover key shapes, this covers the
  // Authorization-scheme shape that traffic bodies carry.
  return redactMobileSecretValues(out)
    .replace(/\bBearer\s+[A-Za-z0-9_\-./+=]+/gi, "Bearer <redacted>")
    .slice(0, maxLen);
}

export interface TrafficScopeVerdict { inScope: boolean; reasons: string[] }

/** §90: only traffic generated by the authorized test app on the
 *  authorized device within the session is in scope. */
export function evaluateTrafficScope(
  record: TrafficRecordInput,
  session: { applicationRef: string; deviceId: string | null },
): TrafficScopeVerdict {
  const reasons: string[] = [];
  if (record.sourceApp !== session.applicationRef) reasons.push("TRAFFIC_SOURCE_MISMATCH: traffic did not originate from the authorized test application (§90)");
  if (session.deviceId && record.sourceDeviceId && record.sourceDeviceId !== session.deviceId) {
    reasons.push("TRAFFIC_DEVICE_MISMATCH: traffic did not originate from the session device (§90)");
  }
  return { inScope: reasons.length === 0, reasons };
}

/** §93: TLS observations from the controlled test environment —
 *  recorded as observations, feeding findings only through the
 *  canonical normalization tail. */
export function tlsObservations(record: TrafficRecordInput): string[] {
  const obs: string[] = [];
  if (record.tls?.cleartext || record.url.toLowerCase().startsWith("http://")) obs.push("CLEARTEXT_TRAFFIC_OBSERVED");
  if (record.tls && record.tls.certificateValid === false) obs.push("CERTIFICATE_VALIDATION_FAILURE_OBSERVED");
  if (record.tls?.version && /^(SSL|TLSv1\.0|TLSv1\.1)\b/i.test(record.tls.version)) obs.push(`DEPRECATED_TLS_VERSION:${record.tls.version}`);
  return obs;
}

/** §92/§44: an observed endpoint is a correlation candidate only —
 *  DISCOVERED_REFERENCE, never authorized for active scanning. */
export function trafficEndpointClassification(): "DISCOVERED_REFERENCE" {
  return "DISCOVERED_REFERENCE";
}
