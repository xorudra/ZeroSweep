#!/usr/bin/env bash
# ZeroSweep safe self-hosted installer/bootstrap (Prompt 40 §201–§205).
#
# Safety contract:
#  - verifies prerequisites (Node 20+, pnpm, PostgreSQL/Redis reachable)
#  - generates CRYPTOGRAPHICALLY SECURE random secrets with openssl/node
#  - NEVER prints secrets to the console (§204)
#  - NEVER hardcodes passwords; refuses to overwrite an existing .env
#  - NEVER disables the firewall, NEVER exposes DB/Redis publicly,
#    NEVER downloads or executes remote scripts
#  - creates directories + config, runs migrations, seeds catalog data
#  - provides a health check at the end
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

fail() { echo "ERROR: $*" >&2; exit 1; }

echo "== ZeroSweep installer =="
echo "Repository: $ROOT"

# --- prerequisites (§201) ---
command -v node >/dev/null || fail "Node.js is required (>= 20)."
NODE_MAJOR="$(node -p 'Number(process.versions.node.split(".")[0])')"
[ "$NODE_MAJOR" -ge 20 ] || fail "Node.js >= 20 required (found $(node -v))."
command -v openssl >/dev/null || fail "openssl is required for secret generation."

# --- configuration ---
if [ -f .env ]; then
  echo ".env already exists — refusing to overwrite existing secrets (§203). Delete it manually if you intend a fresh install."
  exit 1
fi

DATABASE_URL="${DATABASE_URL:-postgresql://dsrclone@127.0.0.1:5432/dsrclone}"
REDIS_URL="${REDIS_URL:-redis://127.0.0.1:6379}"

gen_secret() { openssl rand -hex 32; }

cat > .env <<EOF
# Generated by scripts/install/install.sh — secrets are random per install.
# This file is git-ignored. Never commit it.
NODE_ENV=production
DATABASE_URL=${DATABASE_URL}
REDIS_URL=${REDIS_URL}
API_PORT=4000
JWT_SECRET=$(gen_secret)
JWT_EXPIRES_IN=15m
REFRESH_TOKEN_TTL_DAYS=30
RELEASE_VERSION=1.0.0
# Productization (Prompt 40): set PRODUCT_MODE for this deployment.
PRODUCT_MODE=SELF_HOSTED
# Billing stays unconfigured until a provider is deliberately set (§21):
# PRODUCT_BILLING_PROVIDER=
# PRODUCT_BILLING_WEBHOOK_SECRET=
# Licensing (Ed25519 PUBLIC key only — the private key never ships, §30):
# PRODUCT_LICENSE_PUBLIC_KEY=
PRODUCT_TRIAL_DAYS=14
PRODUCT_TELEMETRY_ENABLED=false
EOF
chmod 600 .env
echo "Wrote .env with freshly generated secrets (values not printed, §204)."

# --- dependencies + build ---
if command -v pnpm >/dev/null; then PNPM="pnpm"; else PNPM="npx pnpm@9.15.0"; fi
echo "Installing dependencies (pinned pnpm 9.15.0)…"
$PNPM install --frozen-lockfile

echo "Generating Prisma client + applying migrations…"
$PNPM --filter @dsrclone/database exec prisma generate
$PNPM --filter @dsrclone/database exec prisma migrate deploy

echo "Seeding catalog + example product plans…"
$PNPM --filter @dsrclone/database exec prisma db seed || $PNPM --filter @dsrclone/database seed

echo "Building…"
$PNPM build

echo "== Health check =="
node scripts/product/health-check.mjs || echo "Health check reported issues — review output above before exposing the API."

cat <<'NEXT'

Install complete. Next steps:
  1. Start the API:      pnpm --filter @dsrclone/api start
  2. Start the worker:    pnpm --filter @dsrclone/worker start
  3. Start the web app:   pnpm --filter @dsrclone/web start
  4. Create the first account via the web UI or POST /api/v1/product/signup.
     Platform administrators are bootstrapped ONLY from the
     PRODUCT_PLATFORM_ADMIN_EMAILS deployment variable (§96).
  5. Read docs/getting-started/quickstart.md and docs/product/configuration.md.

The installer did NOT: open firewall ports, expose PostgreSQL/Redis
publicly, create default passwords, or run any remote script.
NEXT
